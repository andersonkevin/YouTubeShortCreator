#!/usr/bin/env python3
"""Print native data for the pinned, local HyperFrames walking character."""
import argparse
import hashlib
import json
from pathlib import Path

SOURCE_SHA256 = 'b17f487d93636827be00a53124dca0ddb4d16907c1225670d75cb966f5963b9b'


def property_data(prop):
    if prop.get('s') is True:
        if set(prop) != {'s', 'x', 'y'}:
            raise ValueError('Unsupported separated position')
        return {'x': property_data(prop['x']), 'y': property_data(prop['y'])}
    if set(prop) != {'a', 'k'} or prop['a'] not in (0, 1):
        raise ValueError('Unsupported animation property')
    if not prop['a']:
        return {'value': prop['k']}
    frames = prop['k']
    for i, key in enumerate(frames):
        expected = {'t', 's'} if i == len(frames) - 1 else {'t', 's', 'i', 'o'}
        if set(key) != expected or (i and key['t'] <= frames[i - 1]['t']):
            raise ValueError('Unsupported character keyframe')
        if i < len(frames) - 1 and (key['i'] != {'x': [1], 'y': [1]} or key['o'] != {'x': [0], 'y': [0]}):
            raise ValueError('Only the source linear easing is supported')
    return {'keys': [[key['t'], key['s']] for key in frames]}


def convert(data):
    if (data['w'], data['h'], data['fr'], data['ip'], data['op']) != (1920, 1080, 30, 0, 225) or data['assets']:
        raise ValueError('Unexpected character composition')
    colors = {(0.07, 0.09, 0.15, 1): 'front', (0.48, 0.5, 0.53, 1): 'back', (0.99, 0.99, 0.99, 1): 'cutout'}
    identity = {'p': [0, 0], 'a': [0, 0], 's': [100, 100], 'r': 0, 'o': 100, 'sk': 0, 'sa': 0}
    layers = []
    for layer in data['layers']:
        if layer['ty'] not in (3, 4) or any(layer[k] != value for k, value in {'ddd': 0, 'sr': 1, 'ao': 0, 'st': 0, 'bm': 0, 'ip': 0, 'op': 225}.items()):
            raise ValueError('Unsupported character layer')
        shapes = []
        for group in layer.get('shapes', []):
            items = group['it']
            if group['ty'] != 'gr' or [n['ty'] for n in items] not in (['rc', 'fl', 'tr'], ['rc', 'fl', 'st', 'tr'], ['el', 'fl', 'tr'], ['el', 'fl', 'st', 'tr']):
                raise ValueError('Unsupported character shape')
            if {k: property_data(items[-1][k]).get('value') for k in identity} != identity:
                raise ValueError('Character shape group must have its source identity transform')
            shape, fill = items[:2]
            if shape['d'] != 1 or fill['r'] != 1 or property_data(fill['o']) != {'value': 100}:
                raise ValueError('Unsupported character fill')
            record = {'type': shape['ty'], 'position': property_data(shape['p'])['value'],
                      'size': property_data(shape['s'])['value'], 'fill': colors[tuple(property_data(fill['c'])['value'])]}
            if shape['ty'] == 'rc':
                record['radius'] = property_data(shape['r'])['value']
            if len(items) == 4:
                stroke = items[2]
                if stroke['lc'] != 2 or stroke['lj'] != 2 or property_data(stroke['o']) != {'value': 100}:
                    raise ValueError('Unsupported character stroke')
                record['stroke'] = colors[tuple(property_data(stroke['c'])['value'])]
                record['stroke_width'] = property_data(stroke['w'])['value']
            shapes.append(record)
        layers.append({'id': layer['ind'], 'name': layer['nm'], 'parent': layer.get('parent'),
                       'transform': {k: property_data(v) for k, v in layer['ks'].items()}, 'shapes': shapes})
    return {'source_sha256': SOURCE_SHA256, 'fps': 30, 'last_frame': 224, 'layers': layers}


def bundle(source):
    if source.is_symlink() or not source.is_file():
        raise ValueError('Character source must be a regular local file')
    raw = source.read_bytes()
    if hashlib.sha256(raw).hexdigest() != SOURCE_SHA256:
        raise ValueError('Pinned character source hash mismatch')
    data = convert(json.loads(raw))
    return ('// HyperFrames lottie-character-walk, Apache-2.0. See THIRD_PARTY_NOTICES.md.\n'
            '// Generated by tools/vendor_character.py; exact source geometry/keyframes, brand color roles.\n'
            'window.ShortCreatorCharacterData = ' + json.dumps(data, separators=(',', ':')) + ';\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('source', type=Path, help='Pinned local mascot.json; no network or writes')
    print(bundle(parser.parse_args().source), end='')
